const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const run = (name, context) => vm.runInContext(fs.readFileSync(path.join(root, name), 'utf8'), context);
function environment(bridge) {
  const values = new Map();
  return vm.createContext({ window: { KnowKanjiNative: bridge }, URLSearchParams, location: { search: '' },
    localStorage: { getItem: key => values.get(key) || null, setItem: (key, value) => values.set(key, value) } });
}
const messages = [];
const ios = environment();
ios.window.webkit = { messageHandlers: { pengo: { postMessage: message => messages.push(message) } } };
run('ios/Pengo/bridge.js', ios);
run('platform.js', ios);
run('onboarding.js', ios);
assert.equal(ios.window.Platform.isIOSApp, true);
assert.equal(ios.window.Platform.isAndroidApp, false);
assert.equal(ios.window.Platform.isNativeApp, true);
assert.ok(ios.window.Platform.backingStoreNote().includes('on this device'));
assert.equal(ios.shouldShowOnboarding(), true);
ios.markOnboarded();
assert.equal(ios.shouldShowOnboarding(), false);
const native = ios.window.KnowKanjiNative;
const backup = '{"notes":{"字":"quotes \\\" and newline\n"}}';
native.exportJson('pengo-backup.json', backup);
assert.equal(messages.at(-1).method, 'exportJson');
assert.equal(messages.at(-1).args[1], backup);
native.importJson();
assert.equal(messages.at(-1).method, 'importJson');
native.setReminder(true, '20:30');
assert.equal(messages.at(-1).method, 'setReminder');
assert.equal(messages.at(-1).args[0], true);
ios.window.PengoIOSUpdateReminders({ enabled: true, time: '20:30', permission: 'granted', lastDate: '' });
run('reminders.js', ios);
assert.equal(ios.Reminders.read().time, '20:30');
assert.equal(ios.Reminders.permission(), 'granted');
ios.Reminders.syncGoal();
native.resetReminderSettings();
assert.equal(messages.at(-1).method, 'resetReminderSettings');
native.setReminderGoalDate('2026-10-11');
assert.equal(messages.at(-1).args[0], '2026-10-11');
const android = environment({ exportJson() {} });
run('platform.js', android);
run('onboarding.js', android);
assert.equal(android.window.Platform.isAndroidApp, true);
assert.equal(android.window.Platform.isIOSApp, false);
assert.equal(android.shouldShowOnboarding(), true);
const browser = environment();
run('platform.js', browser);
run('onboarding.js', browser);
assert.equal(browser.window.Platform.isNativeApp, false);
assert.equal(browser.shouldShowOnboarding(), false);
browser.location.search = '?onboarding=1';
assert.equal(browser.shouldShowOnboarding(), true);
console.log('iOS bridge, native platform detection, and onboarding checks passed');
