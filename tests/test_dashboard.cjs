const assert = require('node:assert/strict');
global.Course = require('../course.js');
global.Practice = require('../practice.js');
const Dashboard = require('../dashboard.js');
const today = '2026-10-08';
const days = {[today]: {practiced: {'kanji:日':true, 'vocab:word':true, 'grammar:point':true},
  attempts: 7, correct: 4, learned: 1, recalled: {'kanji:日':true}, reviewed:{'kanji:日':true}}};
const s = Dashboard.summary(days, today);
assert.deepEqual(s.counts, {kanji:1,vocab:1,grammar:1});
assert.equal(s.distinct,3); assert.equal(s.attempts,7); assert.equal(s.recalled,1);
assert.deepEqual(Dashboard.summary(days,'2026-10-09').counts,{kanji:0,vocab:0,grammar:0});
assert.equal(Dashboard.challenges(days,today,3,'N5')[0].done,true);
assert.equal(Dashboard.challenges(days,today,5,'N5')[0].done,false);
assert.equal(Dashboard.challenges(days,today,3,'N5')[2].done,false);
const focus = ['2026-10-08','2026-10-09','2026-10-10'].map(date=>Dashboard.challenges(days,date,3,'N4')[1].title);
assert.equal(new Set(focus).size,3);
assert.deepEqual(Dashboard.challenges(days,today,5,'N5'),Dashboard.challenges(days,today,5,'N5'));
assert.equal(Dashboard.dailyIndex(today,100),Dashboard.dailyIndex(today,100));
assert.equal(Dashboard.dailyIndex(today,0),0);
assert.equal(Dashboard.challenges({[today]:{learned:4}},today,3,'N5')[0].done,true);
assert.deepEqual(Dashboard.summary({[today]:{learned:4}},today).counts,{kanji:0,vocab:0,grammar:0});
const c = Practice.config({format:'listening',kind:'vocab'});
assert.equal(c.format,'quiz', 'old listening links fall back to a text quiz');
const session={version:1,id:'old',config:{...c,format:'listening'},questions:[{type:'vocab',id:'a',lv:'N5',variant:0,options:['a','b']}],cursor:0,answers:[]};
assert.equal(Practice.validSession(session,()=>true),false,'retired sessions cannot block practice');
Dashboard.challenges(days,today,5,'N5').forEach(q=>assert.ok(q.href.includes('format=recall')));
const recalled={[today]:{recalled:{'kanji:日':true,'kanji:月':true,'kanji:火':true,'vocab:word':true}}};
assert.equal(Dashboard.challenges(recalled,today,5,'N5')[2].done,true);
assert.equal(Dashboard.challenges(recalled,'2026-10-09',5,'N5')[2].done,false);
const grammarDay = '2026-10-09';
const partial = {[grammarDay]: {practiced:{'grammar:g1':true}}};
const grammarQuest = Dashboard.challenges(partial,grammarDay,5,'N5').find(q=>q.id==='focus');
assert.equal(grammarQuest.kind,'grammar');
assert.equal(grammarQuest.remaining,2);
const challengePool=[{type:'grammar',id:'g1'},{type:'grammar',id:'g2'},{type:'grammar',id:'g2'},{type:'kanji',id:'日'}];
assert.deepEqual(Dashboard.challengeItems(challengePool,grammarQuest,partial[grammarDay]),[{type:'grammar',id:'g2'}]);
const flipQuest=Dashboard.challenges({},grammarDay,5,'N5').find(q=>q.id==='flip');
assert.equal(Dashboard.challengeItems([{type:'kanji',id:'日'}],flipQuest,{practiced:{'kanji:日':true}}).length,1,'flip challenge counts ratings, not prior study');
assert.equal(Dashboard.challengeItems([{type:'kanji',id:'日'}],flipQuest,{recalled:{'kanji:日':true}}).length,0,'flip excludes already rated kanji');
assert.equal(Dashboard.challenges({[grammarDay]:{practiced:{'grammar:g1':true,'grammar:g2':true,'grammar:g3':true}}},grammarDay,5,'N5').find(q=>q.id==='focus').remaining,0);
console.log('Dashboard and discovery rules: passed');
